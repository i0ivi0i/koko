# 设计原则：run.ps1 只保留一个职责：Win11 下启动 Rust 主程序。
# 为什么这样做：
# 1) 启动真相只在 Rust 源码，不在脚本里复制一套“隐藏规则”。
# 2) 发生 bug 时直接查 Rust 主链路，不会被脚本分支和参数魔改干扰。
# 3) 启动器越薄，行为越稳定，可预期性越高，排障路径越短。
# 这么做的好处：
# - 双击或 IDE 启动时入口一致，减少“某入口能复现、某入口不能复现”的漂移。
# - 脚本不承载配置与业务决策，避免责任边界混乱。
# - 未来迁移部署方式时，启动层几乎不需要改动。
Set-Location $PSScriptRoot
& cargo run --bin koko
exit $LASTEXITCODE
