/// 第一阶段共享命令契约：各壳层只能表达意图，不能直接裁决业务真相。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 命令 {
    /// 设备级匿名身份引导：壳层只提交入口凭证，不得自行宣布“我是谁”。
    引导匿名身份 {
        /// 壳层本地持久化的设备入口凭证。
        /// 注意：它只是再次进入系统的钥匙，不是最终身份真相。
        设备匿名凭证: String,
    },
    /// 使用短码进房或建房。短码是否合法由后端领域规则裁决。
    按短码进房或建房 { 房间短码: String },
    /// 在实时主链发送文本消息。消息是否成立由用例+领域+权威存储共同裁决。
    发送文本消息 {
        房间标识: String,
        客户端消息标识: String,
        文本: String,
    },
    /// 后台最小登录命令。第一阶段只做密码门禁，不扩展到完整账号体系。
    后台登录 { 用户名: String, 密码: String },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 命令结果 {
    /// 命令被受理并成功落到权威真相。
    成功,
    /// 命令被拒绝；拒绝原因通过稳定错误码表达，避免壳层误解语义。
    被拒绝 { 错误码: 错误码 },
}

/// 查询只表达“读意图”，不触发业务写入。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 查询 {
    /// 拉取整房快照，用于建立同步基线或补洞失败后的恢复。
    拉取房间快照 { 房间标识: String },
    /// 按位置拉增量事件，是实时续接和补洞的冷路径兜底接口。
    拉取房间增量事件 {
        房间标识: String, 从位置开始: i64
    },
    /// 后台总览查询：返回房间总量和消息总量。
    后台概览,
    /// 后台房间列表查询：返回最近一批房间标识。
    后台房间列表,
    /// 后台房间详情查询：返回单房间统计信息。
    后台房间详情 { 房间标识: String },
}

/// 快照是“某一时刻的权威基线”，不是页面状态。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 快照 {
    /// 匿名身份快照：用于多壳恢复“这个设备当前对应哪个内部身份和花名”。
    匿名身份 {
        /// 后端权威维护的匿名内部身份锚点。
        /// 未来注册只允许链接到它，不允许再造第二个人。
        匿名身份标识: String,
        /// 当前对外展示的花名。
        /// 它可以变化，但永远不是内部主键。
        展示花名: String,
    },
    /// 房间基线快照：必须带最新事件位置锚点。
    房间 {
        /// 稳定房间标识，供冷热路径统一引用。
        房间标识: String,
        /// 房间当前最新事件位置，用于前端续接和补洞。
        最新事件位置: i64,
        /// 当前房间可直接阅读的最近消息基线。
        /// 设计原因：
        /// 1. 刷新回房后，前端不能只拿到 latest_event_position 就假装历史还在；
        /// 2. 首次进入已有历史的房间时，也应该立刻看到最近聊到哪；
        /// 3. 这批消息仍是权威事实，不是前端缓存残影。
        最近消息: Vec<领域事件>,
    },
    /// 房间增量事件快照：冷路径按位置补洞返回。
    房间增量事件 {
        /// 事件所属房间。
        房间标识: String,
        /// 已成立领域事件序列（按位置升序）。
        事件: Vec<领域事件>,
        /// 查询时刻的最新事件位置锚点。
        最新事件位置: i64,
    },
    /// 房间历史分页：用于“当前最老这条之前，再取一页更早消息”。
    房间历史页 {
        /// 历史页所属房间。
        房间标识: String,
        /// 当前这一页消息，固定按 event_position 升序返回。
        消息: Vec<领域事件>,
    },
    后台概览 {
        /// 当前房间总数。
        房间总数: u64,
        /// 当前消息总数。
        消息总数: u64,
    },
    后台房间列表 {
        /// 房间标识列表（后台展示用）。
        房间标识列表: Vec<String>,
    },
    后台房间详情 {
        /// 被查询房间标识。
        房间标识: String,
        /// 当前最新事件位置。
        最新事件位置: i64,
        /// 房间消息累计数量。
        消息总数: u64,
    },
}

/// 匿名身份引导结果：
/// 用于把“设备入口凭证 -> 匿名内部身份 -> 当前稳定会话锚点”一次性交给壳层。
///
/// 边界约束：
/// 1. `匿名身份标识` 才是未来注册要链接的内部身份；
/// 2. `展示花名` 只是当前显示名，不是主键；
/// 3. `会话标识` 是当前 MVP 复用现有冷/热路径所需的运行锚点。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 匿名身份引导结果 {
    /// 后端权威维护的匿名内部身份锚点。
    pub 匿名身份标识: String,
    /// 当前展示给其他成员的花名。
    pub 展示花名: String,
    /// 当前设备恢复出的稳定会话锚点。
    pub 会话标识: String,
}

/// 领域事件只代表“已成立的业务事实”。
/// 注意：ack/订阅成功/补洞指令都不是领域事件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 领域事件 {
    消息已创建 {
        /// 事件所属房间。
        房间标识: String,
        /// 服务端权威消息标识。
        消息标识: String,
        /// 客户端上报的幂等消息标识。
        客户端消息标识: String,
        /// 发送者会话标识。
        发送者会话标识: String,
        /// 发送者当前展示花名。
        /// 注意：它不是内部身份主键，只是群聊展示投影。
        发送者花名: String,
        /// 消息文本事实。
        文本: String,
        /// 事件在房间流中的单调递增位置。
        事件位置: i64,
    },
}

/// 控制面结果用于表达“同步控制语义”，与领域事件强制分离。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 控制面结果 {
    /// 建立订阅后告诉客户端当前起始位置，便于续接。
    订阅已建立 {
        /// 订阅目标房间。
        房间标识: String,
        /// 本次订阅从哪个事件位置开始续接。
        起始位置: i64,
    },
    /// 客户端发现缺口且无法靠当前增量闭合时，要求回退到快照重拉。
    需要重拉快照 {
        /// 发生缺口的房间。
        房间标识: String,
        /// 客户端期望但当前无法闭合的事件位置。
        期望位置: i64,
    },
}

/// 错误码是跨壳稳定失败语义，不绑定任何页面文案。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 错误码 {
    /// 启动或运行需要的关键配置缺失。
    配置缺失,
    /// 输入参数不满足契约或领域规则。
    参数非法,
    /// 会话不存在或已失效。
    会话无效,
    /// 房间不存在。
    房间不存在,
    /// 不具备房间成员资格。
    成员资格不足,
    /// 未归类的系统异常。
    系统错误,
}
