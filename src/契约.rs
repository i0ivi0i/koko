/// 第一阶段共享命令契约：各壳层只能表达意图，不能直接裁决业务真相。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 命令 {
    /// 创建匿名会话，属于冷路径命令。
    引导匿名会话,
    /// 使用短码进房或建房。短码是否合法由后端领域规则裁决。
    按短码进房或建房 { 房间短码: String },
    /// 在实时主链发送文本消息。消息是否成立由用例+领域+权威存储共同裁决。
    发送文本消息 {
        房间标识: String,
        客户端消息标识: String,
        文本: String,
    },
    /// 后台最小登录命令。第一阶段只做密码门禁，不扩展到完整账号体系。
    后台登录 { 用户名: String, 密码: String },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 命令结果 {
    /// 命令被受理并成功落到权威真相。
    成功,
    /// 命令被拒绝；拒绝原因通过稳定错误码表达，避免壳层误解语义。
    被拒绝 { 错误码: 错误码 },
}

/// 查询只表达“读意图”，不触发业务写入。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 查询 {
    /// 拉取整房快照，用于建立同步基线或补洞失败后的恢复。
    拉取房间快照 {
        房间标识: String,
    },
    /// 按位置拉增量事件，是实时续接和补洞的冷路径兜底接口。
    拉取房间增量事件 {
        房间标识: String,
        从位置开始: i64,
    },
    后台概览,
    后台房间列表,
    后台房间详情 {
        房间标识: String,
    },
}

/// 快照是“某一时刻的权威基线”，不是页面状态。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 快照 {
    /// 会话快照：前端只能拿来持有 session_id，不得扩展为权限真相。
    会话 {
        会话标识: String,
        显示名: String,
    },
    /// 房间基线快照：必须带最新事件位置锚点。
    房间 {
        房间标识: String,
        最新事件位置: i64,
    },
    /// 房间增量事件快照：冷路径按位置补洞返回。
    房间增量事件 {
        房间标识: String,
        事件: Vec<领域事件>,
        最新事件位置: i64,
    },
    后台概览 {
        房间总数: u64,
        消息总数: u64,
    },
    后台房间列表 {
        房间标识列表: Vec<String>,
    },
    后台房间详情 {
        房间标识: String,
        最新事件位置: i64,
        消息总数: u64,
    },
}

/// 领域事件只代表“已成立的业务事实”。
/// 注意：ack/订阅成功/补洞指令都不是领域事件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 领域事件 {
    消息已创建 {
        房间标识: String,
        消息标识: String,
        客户端消息标识: String,
        发送者会话标识: String,
        文本: String,
        事件位置: i64,
    },
}

/// 控制面结果用于表达“同步控制语义”，与领域事件强制分离。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 控制面结果 {
    /// 建立订阅后告诉客户端当前起始位置，便于续接。
    订阅已建立 {
        房间标识: String, 起始位置: i64
    },
    /// 客户端发现缺口且无法靠当前增量闭合时，要求回退到快照重拉。
    需要重拉快照 {
        房间标识: String, 期望位置: i64
    },
}

/// 错误码是跨壳稳定失败语义，不绑定任何页面文案。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 错误码 {
    配置缺失,
    参数非法,
    会话无效,
    房间不存在,
    成员资格不足,
    系统错误,
}
