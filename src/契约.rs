/// 第一阶段共享命令契约：各壳层只能表达意图，不能直接裁决业务真相。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 命令 {
    /// 设备级匿名身份引导：壳层只提交入口凭证，不得自行宣布“我是谁”。
    引导匿名身份 {
        /// 壳层本地持久化的设备入口凭证。
        /// 注意：它只是再次进入系统的钥匙，不是最终身份真相。
        设备匿名凭证: String,
    },
    /// 使用短码进房或建房。短码是否合法由后端领域规则裁决。
    按短码进房或建房 { 房间短码: String },
    /// 在实时主链发送文本消息。消息是否成立由用例+领域+权威存储共同裁决。
    发送文本消息 {
        房间标识: String,
        客户端消息标识: String,
        文本: String,
    },
    /// 推进当前身份在某个房间里的阅读位置。
    /// 注意：这是用户级阅读真相，不是页面滚动条位置。
    推进房间阅读位置 {
        /// 目标房间。
        房间标识: String,
        /// 本次确认已读到的最大事件位置。
        /// 约束：它只能单调前进，不能回退。
        已读到事件位置: i64,
    },
    /// 后台最小登录命令。第一阶段只做密码门禁，不扩展到完整账号体系。
    后台登录 { 用户名: String, 密码: String },
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 命令结果 {
    /// 命令被受理并成功落到权威真相。
    成功,
    /// 命令被拒绝；拒绝原因通过稳定错误码表达，避免壳层误解语义。
    被拒绝 { 错误码: 错误码 },
}

/// 查询只表达“读意图”，不触发业务写入。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 查询 {
    /// 拉取整房快照，用于建立同步基线或补洞失败后的恢复。
    拉取房间快照 { 房间标识: String },
    /// 按位置拉增量事件，是实时续接和补洞的冷路径兜底接口。
    拉取房间增量事件 {
        房间标识: String, 从位置开始: i64
    },
    /// 后台总览查询：返回房间总量和消息总量。
    后台概览,
    /// 后台房间列表查询：返回最近一批房间标识。
    后台房间列表,
    /// 后台房间详情查询：返回单房间统计信息。
    后台房间详情 { 房间标识: String },
}

/// 快照是“某一时刻的权威基线”，不是页面状态。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 快照 {
    /// 匿名身份快照：用于多壳恢复“这个设备当前对应哪个内部身份和花名”。
    匿名身份 {
        /// 后端权威维护的匿名内部身份锚点。
        /// 未来注册只允许链接到它，不允许再造第二个人。
        匿名身份标识: String,
        /// 当前对外展示的花名。
        /// 它可以变化，但永远不是内部主键。
        展示花名: String,
    },
    /// 房间基线快照：必须带最新事件位置锚点。
    房间 {
        /// 稳定房间标识，供冷热路径统一引用。
        房间标识: String,
        /// 房间当前最新事件位置，用于前端续接和补洞。
        最新事件位置: i64,
        /// 当前身份上次已读到的事件位置。
        /// `None` 表示这个身份在该房间还没有建立阅读锚点。
        上次已读事件位置: Option<i64>,
        /// 当前首屏中的第一条未读事件位置。
        /// `None` 表示本次恢复不展示未读分隔条。
        首条未读事件位置: Option<i64>,
        /// 当前首屏消息。
        /// 它不再固定等于“最近 55 条”，而是围绕未读起点或最近消息窗口返回。
        首屏消息: Vec<领域事件>,
        /// 当前首屏上方是否仍然存在更早历史。
        /// 这是真实查询结果，不是前端根据数组长度猜出来的。
        首屏前仍有更早历史: bool,
    },
    /// 房间增量事件快照：冷路径按位置补洞返回。
    房间增量事件 {
        /// 事件所属房间。
        房间标识: String,
        /// 已成立领域事件序列（按位置升序）。
        事件: Vec<领域事件>,
        /// 查询时刻的最新事件位置锚点。
        最新事件位置: i64,
    },
    /// 房间历史分页：用于“当前最老这条之前，再取一页更早消息”。
    房间历史页 {
        /// 历史页所属房间。
        房间标识: String,
        /// 当前这一页消息，固定按 event_position 升序返回。
        消息: Vec<领域事件>,
    },
    后台概览 {
        /// 当前房间总数。
        房间总数: u64,
        /// 当前消息总数。
        消息总数: u64,
    },
    后台房间列表 {
        /// 房间标识列表（后台展示用）。
        房间标识列表: Vec<String>,
    },
    后台房间详情 {
        /// 被查询房间标识。
        房间标识: String,
        /// 当前最新事件位置。
        最新事件位置: i64,
        /// 房间消息累计数量。
        消息总数: u64,
    },
}

/// 匿名身份引导结果：
/// 用于把“设备入口凭证 -> 当前资料投影 -> 当前稳定会话锚点”一次性交给壳层。
///
/// 边界约束：
/// 1. 匿名内部身份只留在后端与持久化层，不进入共享契约；
/// 2. `展示花名` 只是当前显示名，不是主键；
/// 3. `会话标识` 是当前 MVP 复用现有冷/热路径所需的运行锚点。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 匿名身份引导结果 {
    /// 当前展示给其他成员的花名。
    pub 展示花名: String,
    /// 当前设备恢复出的稳定会话锚点。
    pub 会话标识: String,
}

/// 统一附件平台对外暴露的最小附件种类。
/// 当前最小媒体切片先点亮图片和视频，其余种类后续再按同一主链接入。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 附件类型 {
    图片,
    视频,
}

/// 图片附件快照只承载聊天时间线渲染所需的最小事实。
/// 这里故意不暴露对象存储 key、签名 URL、缩略图存储实现等 adapter 私货。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 图片附件快照 {
    pub 附件标识: String,
    pub 宽: i32,
    pub 高: i32,
}

/// 视频附件快照沿用与图片相同的最小稳定渲染事实。
/// 这里先不携带时长、locator、peer 等运行态，避免把媒体传输细节倒灌进共享契约。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 视频附件快照 {
    pub 附件标识: String,
    pub 宽: i32,
    pub 高: i32,
}

/// 统一附件快照：消息只引用附件真相，不直接内嵌文件存储细节。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 附件快照 {
    图片(图片附件快照),
    视频(视频附件快照),
}

/// 统一媒体资产种类：
/// 1. 图片走 blob 资产主链；
/// 2. 视频/音频走流媒体资产主链；
/// 3. 这里只描述稳定共享语义，不携带某个壳专属的播放器状态。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 媒体资产种类 {
    图片Blob,
    流媒体视频,
    流媒体音频,
}

/// 变体描述是 blob 资产的稳定读取面。
/// 它只回答“这个变体是什么、从哪里读”，不回答缓存策略和壳层展示逻辑。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 变体描述 {
    pub 标识: String,
    pub mime_type: String,
    pub 地址: String,
    pub 宽: Option<i32>,
    pub 高: Option<i32>,
}

/// 流媒体清单描述只表达标准主入口。
/// HLS/DASH 哪一条被某个端优先消费，是 adapter/runtime 的职责，不是共享 contract 的职责。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 媒体清单描述 {
    pub hls主清单地址: Option<String>,
    pub dash主清单地址: Option<String>,
}

/// 分发表面只暴露跨端共享所需的 swarm 线索。
/// 这里不塞本地存储键、页面 session 或某个端专属 ticket 语义。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 媒体分发描述 {
    pub swarm_id: String,
    pub announce_urls: Vec<String>,
    pub web_seed_url: Option<String>,
    pub join_ticket: Option<String>,
}

/// 冷源角色是领域语义，不是页面流程。
/// 目前只点亮“冷备引导”这一条，显式表达原始文件不会长期担任正式主链。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 媒体冷源角色 {
    冷备引导,
}

/// 冷源描述只回答：
/// 1. 原始冷源地址是什么；
/// 2. 到什么时候过期；
/// 3. 当前还能不能用；
/// 4. 它在协议里扮演什么角色。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 媒体冷源描述 {
    pub 原始地址: Option<String>,
    pub 到期时间戳秒: i64,
    pub 是否可用: bool,
    pub 角色: 媒体冷源角色,
}

/// 流媒体资产描述是视频/音频主链的共享入口。
/// 它把 manifest、分发和平滑退化所需的冷源窗口一次收口，避免后续继续回到“单个 src 真相”。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct 流媒体资产描述 {
    pub 资产标识: String,
    pub 内容哈希: String,
    pub 种类: 媒体资产种类,
    pub 清单: 媒体清单描述,
    pub 分发: 媒体分发描述,
    pub 冷源: 媒体冷源描述,
}

/// Blob 资产描述是图片/GIF/静态大图的统一表面。
/// preview/full/original 是稳定资产层级，不是壳层自己拼出来的三个 URL。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Blob媒体资产描述 {
    pub 资产标识: String,
    pub 内容哈希: String,
    pub 种类: 媒体资产种类,
    pub preview: Option<变体描述>,
    pub full: Option<变体描述>,
    pub original: Option<变体描述>,
    pub 分发: Option<媒体分发描述>,
    pub 冷源: 媒体冷源描述,
}

/// 领域事件只代表“已成立的业务事实”。
/// 注意：ack/订阅成功/补洞指令都不是领域事件。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 领域事件 {
    消息已创建 {
        /// 事件所属房间。
        房间标识: String,
        /// 服务端权威消息标识。
        消息标识: String,
        /// 客户端上报的幂等消息标识。
        客户端消息标识: String,
        /// 发送者会话标识。
        发送者会话标识: String,
        /// 发送者当前展示花名。
        /// 注意：它不是内部身份主键，只是群聊展示投影。
        发送者花名: String,
        /// 消息文本事实。
        文本: String,
        /// 这条消息引用的附件快照。
        /// 第一阶段只会出现图片，但事件语义已经统一成“文本 + 附件”。
        附件: Vec<附件快照>,
        /// 事件在房间流中的单调递增位置。
        事件位置: i64,
    },
}

/// 控制面结果用于表达“同步控制语义”，与领域事件强制分离。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 控制面结果 {
    /// 建立订阅后告诉客户端当前起始位置，便于续接。
    订阅已建立 {
        /// 订阅目标房间。
        房间标识: String,
        /// 本次订阅从哪个事件位置开始续接。
        起始位置: i64,
    },
    /// 客户端发现缺口且无法靠当前增量闭合时，要求回退到快照重拉。
    需要重拉快照 {
        /// 发生缺口的房间。
        房间标识: String,
        /// 客户端期望但当前无法闭合的事件位置。
        期望位置: i64,
    },
}

/// 错误码是跨壳稳定失败语义，不绑定任何页面文案。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum 错误码 {
    /// 启动或运行需要的关键配置缺失。
    配置缺失,
    /// 输入参数不满足契约或领域规则。
    参数非法,
    /// 会话不存在或已失效。
    会话无效,
    /// 房间不存在。
    房间不存在,
    /// 不具备房间成员资格。
    成员资格不足,
    /// 附件不存在。
    附件不存在,
    /// 附件不属于当前发送者。
    附件不属于当前发送者,
    /// 附件尚未达到可发送状态。
    附件未就绪,
    /// 当前阶段不允许把该类型附件挂进消息。
    附件类型不支持,
    /// 单条消息里的附件数量超出约束。
    附件数量超限,
    /// 未归类的系统异常。
    系统错误,
}
