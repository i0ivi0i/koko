use crate::{domain, shared::contract};

/// 共享应用根现在只保留真正跨子域稳定复用的最小公共语义。
///
/// 2026-05-04 这轮收口的硬约束：
/// 1. 不再在这里定义跨身份 / 房间 / 消息 / 媒体 / 恢复 / 实时的总仓储口；
/// 2. 每个 bounded context 自己声明自己真正拥有的端口；
/// 3. 这里最多只保留不会把 owner 再吸回来的公共错误映射。
///
/// 这样做不是“为了拆而拆”，而是为了避免任何新能力默认先长回共享大口，
/// 最终把应用层重新挤成一个看起来干净、实际上什么都知道的总中心。
pub(crate) fn 映射领域错误(err: domain::领域错误) -> contract::错误码 {
    match err {
        domain::领域错误::成员资格不足 => contract::错误码::成员资格不足,
        domain::领域错误::消息文本为空
        | domain::领域错误::消息内容为空
        | domain::领域错误::房间短码非法 => contract::错误码::参数非法,
        domain::领域错误::附件类型不支持 => contract::错误码::附件类型不支持,
        domain::领域错误::附件数量超限 => contract::错误码::附件数量超限,
        domain::领域错误::消息文本过长 => contract::错误码::消息文本过长,
    }
}
