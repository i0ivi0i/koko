/// 领域层错误：只表达业务不变量失败，不表达传输层或数据库细节。
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum 领域错误 {
    /// 会话不是房间当前成员，不能发言。
    成员资格不足,
    /// 文本消息去除空白后为空，不允许成立。
    消息文本为空,
    /// 统一消息在文本和附件都为空时，不允许成立。
    消息内容为空,
    /// 第一阶段只允许图片附件进入消息主链。
    附件类型不支持,
    /// 单条消息里的附件数量超过当前约束。
    附件数量超限,
    /// 房间短码不满足长度或字符集规则。
    房间短码非法,
}
