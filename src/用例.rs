use crate::{contract, domain};

/// 用例层只编排业务动作，持久化细节通过端口下沉到适配层实现。
///
/// 维护者说明：
/// - 这个 trait 是“应用层对持久化的最小依赖面”。
/// - 新增仓储方法前，先确认是否真属于应用层编排所需能力。
/// - 不要在端口里泄漏 SQL/HTTP/socket 类型。
pub trait 仓储端口 {
    /// 创建匿名会话并返回会话快照。
    /// 约束：只负责落库和回传事实，不在仓储层生成业务分支判断。
    fn 创建匿名会话(
        &mut self, 显示名: &str
    ) -> Result<contract::快照, contract::错误码>;

    /// 按短码进房或建房并返回房间快照。
    /// 约束：短码合法性由领域层先校验，这里只执行持久化事实写入。
    fn 按短码进房或建房(
        &mut self,
        会话标识: &str,
        房间短码: &str,
    ) -> Result<contract::快照, contract::错误码>;

    /// 查询“会话是否存在”这一基础事实。
    /// 约束：这里只回答会话有效性，不扩展成连接态或页面态判断。
    fn 检查会话存在(&self, 会话标识: &str) -> Result<bool, contract::错误码>;

    /// 查询“会话是否为当前房间成员”这一只读事实。
    /// 约束：不要在仓储层把这个事实扩展成复杂权限决策。
    fn 检查成员资格(
        &self,
        房间标识: &str,
        会话标识: &str,
    ) -> Result<bool, contract::错误码>;

    /// 拉取房间基线快照。
    /// 约束：返回“当前权威锚点”，用于首屏基线和补洞兜底。
    fn 拉取房间快照(
        &self, 房间标识: &str
    ) -> Result<contract::快照, contract::错误码>;

    /// 以事务方式提交“消息已创建”领域事件。
    /// 约束：客户端消息标识用于幂等链路追踪，不可被仓储静默丢弃。
    fn 创建消息事件(
        &mut self,
        房间标识: &str,
        客户端消息标识: &str,
        会话标识: &str,
        文本: &str,
    ) -> Result<contract::领域事件, contract::错误码>;
}

/// 引导匿名会话用例：
/// 由应用层发起“创建会话”意图，并拿回最小会话快照给壳层持有。
pub fn 引导匿名会话(
    仓储: &mut dyn 仓储端口,
    显示名: &str,
) -> Result<contract::快照, contract::错误码> {
    // 最小编排：直接交给仓储创建会话快照。
    仓储.创建匿名会话(显示名)
}

/// 进房/建房主链：
/// 1. 先在领域层校验短码语义
/// 2. 再进入仓储完成事实写入
pub fn 按短码进房或建房(
    仓储: &mut dyn 仓储端口,
    会话标识: &str,
    房间短码: &str,
) -> Result<contract::快照, contract::错误码> {
    domain::room::校验房间短码(房间短码).map_err(映射领域错误)?;
    仓储.按短码进房或建房(会话标识, 房间短码)
}

/// realtime 连接会话校验：
/// 只确认“连接携带的会话是否存在”，不在这里混入成员资格或房间权限。
pub fn 校验实时连接会话(
    仓储: &dyn 仓储端口,
    会话标识: &str,
) -> Result<(), contract::错误码> {
    let exists = 仓储.检查会话存在(会话标识)?;
    if exists {
        Ok(())
    } else {
        Err(contract::错误码::会话无效)
    }
}

/// 加载房间快照用例：
/// 先验证成员资格，再返回基线快照，防止未入房会话越权读取房间事实。
pub fn 加载房间快照(
    仓储: &dyn 仓储端口,
    房间标识: &str,
    会话标识: &str,
) -> Result<contract::快照, contract::错误码> {
    // 先验证成员资格，再返回快照，避免未入房会话直接读取房间真相。
    校验房间订阅资格(仓储, 房间标识, 会话标识)?;
    仓储.拉取房间快照(房间标识)
}

/// realtime / 冷路径共用的订阅资格校验。
/// 约束：房间成员真相只由应用层查询并裁决，handler 不得私自判断。
pub fn 校验房间订阅资格(
    仓储: &dyn 仓储端口,
    房间标识: &str,
    会话标识: &str,
) -> Result<(), contract::错误码> {
    let is_member = 仓储.检查成员资格(房间标识, 会话标识)?;
    domain::member::校验成员可发言(is_member).map_err(映射领域错误)
}

/// 发送文本消息主链：
/// 1. 参数合法性（客户端消息 ID 不能为空）
/// 2. 成员资格校验
/// 3. 文本不变量校验
/// 4. 交给仓储在权威存储内提交事件
pub fn 发送文本消息(
    仓储: &mut dyn 仓储端口,
    房间标识: &str,
    会话标识: &str,
    客户端消息标识: &str,
    文本: &str,
) -> Result<contract::领域事件, contract::错误码> {
    // client_message_id 是幂等锚点的一部分，不能为空。
    if 客户端消息标识.trim().is_empty() {
        return Err(contract::错误码::参数非法);
    }
    校验房间订阅资格(仓储, 房间标识, 会话标识)?;
    let msg = domain::message::创建文本消息(true, 文本).map_err(映射领域错误)?;
    仓储.创建消息事件(房间标识, 客户端消息标识, 会话标识, &msg.文本)
}

/// 领域错误 -> 契约错误码映射。
/// 约束：这里只做语义映射，不改动错误事实本身。
fn 映射领域错误(err: domain::领域错误) -> contract::错误码 {
    match err {
        domain::领域错误::成员资格不足 => contract::错误码::成员资格不足,
        domain::领域错误::消息文本为空 | domain::领域错误::房间短码非法 => {
            contract::错误码::参数非法
        }
    }
}
