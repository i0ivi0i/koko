import {
  房间滚动器,
  type 房间滚动器依赖,
  type 房间滚动器宿主,
} from "./滚动器.js";

/**
 * 时间线业务入口先承接“房间滚动 owner”的装配职责。
 * 这样聊天应用内核不必再直接知道具体滚动器类名，只消费时间线应用暴露的稳定入口。
 */
export type 房间滚动应用依赖 = 房间滚动器依赖;

/**
 * 第一阶段不重写滚动算法，只先把 owner 装配面从聊天应用内核里抽出来。
 * 真正的 DOM 查询和可见锚点裁决仍留在 `房间滚动器` 内部，避免制造第二份滚动逻辑。
 */
export function 创建房间滚动应用(
  宿主: 房间滚动器宿主,
  依赖: 房间滚动应用依赖
): 房间滚动器 {
  return new 房间滚动器(宿主, 依赖);
}
