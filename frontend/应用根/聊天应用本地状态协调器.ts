import type { 房间恢复编排依赖 } from "../恢复/壳层/房间恢复编排.js";
import type { 房间实时编排依赖 } from "../实时/应用.js";
import type { 阅读推进编排依赖 } from "../房间/壳层/阅读推进.js";
import type {
  聊天会话状态,
  聊天时间线状态,
  聊天流程状态,
  聊天运行时状态,
  聊天视口状态,
  聊天输入状态,
} from "./聊天状态.js";
import {
  投影恢复编排状态,
  投影实时编排状态,
  投影阅读推进状态,
  type 房间壳补丁,
} from "./聊天内核状态投影.js";
import {
  应用聊天本地状态折叠,
  type 聊天本地状态补丁,
} from "./聊天本地状态折叠.js";

export interface 聊天应用状态箱 {
  会话状态: 聊天会话状态;
  输入状态: 聊天输入状态;
  时间线状态: 聊天时间线状态;
  视口状态: 聊天视口状态;
  流程状态: 聊天流程状态;
  运行时状态: 聊天运行时状态;
}

export interface 聊天应用本地状态协调器依赖 {
  读取状态箱(): 聊天应用状态箱;
  写回状态箱(next: Partial<聊天应用状态箱>): void;
  读取房间壳补丁(): 房间壳补丁;
  同步消息附件播放结果(): void;
  请求重渲染(): void;
  发送恢复基线同步(firstUnreadEventPosition: number | null): void;
  同步房间视口快照(): void;
}

export interface 聊天应用本地状态协调器 {
  读取恢复状态(): ReturnType<房间恢复编排依赖["读取恢复状态"]>;
  写入恢复状态(
    patch: Parameters<房间恢复编排依赖["写入恢复状态"]>[0]
  ): void;
  读取实时状态(): ReturnType<房间实时编排依赖["读取实时状态"]>;
  写入实时状态(
    patch: Parameters<房间实时编排依赖["写入实时状态"]>[0]
  ): void;
  读取阅读状态(): ReturnType<阅读推进编排依赖["读取阅读状态"]>;
  写入阅读状态(
    patch: Parameters<阅读推进编排依赖["写入阅读状态"]>[0]
  ): void;
  写入本地状态(patch: 聊天本地状态补丁): boolean;
}

/**
 * 聊天应用本地状态协调器只拥有两件事：
 * 1. 把 patch 写回会话 / 输入 / 时间线 / 视口 / 流程 / 运行时六个状态箱；
 * 2. 把 recovery / realtime / 阅读推进三条编排口需要的投影视图统一收口。
 *
 * 它不拥有业务命令，也不拥有 transport / DOM / 平台实现。
 * 这样聊天应用内核可以退回更薄的组合根，不再自己同时兼任状态写入器和编排视图翻译器。
 */
export function 创建聊天应用本地状态协调器(
  deps: 聊天应用本地状态协调器依赖
): 聊天应用本地状态协调器 {
  const 写入本地状态 = (patch: 聊天本地状态补丁): boolean => {
    const 当前状态 = deps.读取状态箱();
    const 结果 = 应用聊天本地状态折叠(当前状态, patch);
    if (!结果.写入了本地补丁) {
      return false;
    }
    deps.写回状态箱({
      ...(结果.会话状态 ? { 会话状态: 结果.会话状态 } : {}),
      ...(结果.输入状态 ? { 输入状态: 结果.输入状态 } : {}),
      ...(结果.时间线状态 ? { 时间线状态: 结果.时间线状态 } : {}),
      ...(结果.视口状态 ? { 视口状态: 结果.视口状态 } : {}),
      ...(结果.流程状态 ? { 流程状态: 结果.流程状态 } : {}),
      ...(结果.运行时状态 ? { 运行时状态: 结果.运行时状态 } : {}),
    });
    if (结果.消息列表发生变化) {
      deps.同步消息附件播放结果();
    }
    deps.请求重渲染();
    return true;
  };

  return {
    读取恢复状态(): ReturnType<房间恢复编排依赖["读取恢复状态"]> {
      const 当前状态 = deps.读取状态箱();
      return 投影恢复编排状态({
        会话状态: 当前状态.会话状态,
        输入状态: 当前状态.输入状态,
        时间线状态: 当前状态.时间线状态,
        视口状态: 当前状态.视口状态,
        流程状态: 当前状态.流程状态,
        房间壳: deps.读取房间壳补丁(),
      });
    },

    写入恢复状态(
      patch: Parameters<房间恢复编排依赖["写入恢复状态"]>[0]
    ): void {
      写入本地状态(patch);
      if (
        Object.hasOwn(patch, "initialUnreadSettled") &&
        patch.initialUnreadSettled === false &&
        Object.hasOwn(patch, "firstUnreadEventPosition")
      ) {
        deps.发送恢复基线同步(patch.firstUnreadEventPosition ?? null);
        deps.同步房间视口快照();
      }
    },

    读取实时状态(): ReturnType<房间实时编排依赖["读取实时状态"]> {
      const 当前状态 = deps.读取状态箱();
      return 投影实时编排状态({
        会话状态: 当前状态.会话状态,
        输入状态: 当前状态.输入状态,
        时间线状态: 当前状态.时间线状态,
        视口状态: 当前状态.视口状态,
        流程状态: 当前状态.流程状态,
        房间壳: deps.读取房间壳补丁(),
      });
    },

    写入实时状态(
      patch: Parameters<房间实时编排依赖["写入实时状态"]>[0]
    ): void {
      写入本地状态(patch);
    },

    读取阅读状态(): ReturnType<阅读推进编排依赖["读取阅读状态"]> {
      const 当前状态 = deps.读取状态箱();
      return 投影阅读推进状态({
        时间线状态: 当前状态.时间线状态,
        视口状态: 当前状态.视口状态,
        房间壳: deps.读取房间壳补丁(),
      });
    },

    写入阅读状态(
      patch: Parameters<阅读推进编排依赖["写入阅读状态"]>[0]
    ): void {
      写入本地状态(patch);
    },

    写入本地状态,
  };
}
