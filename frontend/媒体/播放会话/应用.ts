import {
  创建聊天媒体编排,
  type 聊天媒体快照,
  type 聊天媒体编排端口,
} from "../../聊天媒体编排.js";

/**
 * 媒体播放会话应用门面先把“消息流自动播 / 查看器 / 媒体草稿 / 协作分发预算”统一收在一条入口上：
 * 1. 聊天内核以后只依赖这个显式媒体应用，不再长期直连 `聊天媒体编排.ts`；
 * 2. 当前阶段仍复用成熟的媒体编排实现，先把 owner 入口收窄，再继续拆查看器和协作分发子门面；
 * 3. 这样可以先稳定依赖方向，避免一轮里同时重写媒体主链行为。
 */
export type 媒体播放会话应用依赖 = Parameters<typeof 创建聊天媒体编排>[0];
export type 媒体播放会话应用端口 = 聊天媒体编排端口;
export type 媒体播放会话快照 = 聊天媒体快照;

export function 创建媒体播放会话应用(
  deps: 媒体播放会话应用依赖
): 媒体播放会话应用端口 {
  return 创建聊天媒体编排(deps);
}
